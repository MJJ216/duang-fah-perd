const elemPoolOf = (element) => REMEDY_POOL[element] || REMEDY_POOL['ดิน'];

// เลือกด้วย seed เฉพาะ "คน + วัน" เพื่อให้เปลี่ยนรายวัน
const dailySeed = (seed, date) => (date ? `${seed}|${date}` : seed);

// ===== โหมดเช็คความบาป =====
// meta: { nickname, element, zodiacName, sin, nameNum, dayColor, birthDay, moon, seed, date, pastWeather, hasRainGear }
export const sinFallback = (meta = {}) => {
  const { element = 'ดิน', zodiacName, sin = 50, nameNum = 5, dayColor = null, birthDay = null, moon, pastWeather, hasRainGear, date } = meta;
  const seed = meta.seed || `${meta.nickname || ''}:${zodiacName || ''}:${element}`;
  const dSeed = dailySeed(seed, date);
  const b = bucket(sin);

  const opener = pick(OPENER[b], dSeed, 'open');
  const elem = pick(ELEM_INSIGHT[element] || ELEM_INSIGHT['ดิน'], seed, 'elem');
  const zf = pick(ZODIAC_FLAVOR[zodiacGroup(zodiacName)], seed, 'zod') || '';

  // ประโยคเสริม (เลือกบางส่วนเพื่อให้ความยาวและลำดับต่างกัน)
  const extras = [
    ZODIAC_QUIP[zodiacName],
    pick(NAME_QUIP[nameGroup(nameNum)], seed, 'name'),
    birthDay?.dayName ? DAY_QUIP[birthDay.dayName] : null,
    hasRainGear ? pick(RAIN_GEAR_QUIP[hasRainGear] || [], seed, 'gear') : null,
    pastWeather ? pick(PAST_QUIP[pastWeather] || [], seed, 'past') : null,
    moon ? pick(MOON_LINE[moon.idx] || [], dSeed, 'moon') : null,
  ].filter(Boolean);
  // เลือก 3 ประโยค และสลับลำดับตาม seed
  const chosen = pickN(extras, Math.min(3, extras.length), dSeed, 'ex');
  chosen.sort((a, c) => hashStr(`${dSeed}|${a}`) - hashStr(`${dSeed}|${c}`));

  const closer = pick(CLOSER[b], dSeed, 'close');
  const analysis = `${opener} ${elem}${zf} ${chosen.join(' ')} ${closer}`.replace(/\s+/g, ' ').trim();

  const { remedies, tier } = buildRemedies({ element, seed: dSeed, dayColor, sin, elemPool: elemPoolOf(element) });
  return { analysis, remedies, remedyTier: tier, charm: charmOf(element, seed), fallback: true };
};

