// รวมของมงคลเป็นข้อความแก้เคล็ด
const buildRemedies = (element, seed, dayColor) => {
  const key = REMEDY_POOL[element] ? element : 'ดิน';
  const base = pickN(REMEDY_POOL[key], 3, seed, 'rem');
  const charm = charmOf(element, seed);
  const colorLine = dayColor
    ? `ใส่สีมงคลประจำวันเกิด (${dayColor.name}) หรือสี${charm.color.split(' ')[0]} วันเดินทาง`
    : `ใส่สีมงคล ${charm.color} วันเดินทาง`;
  return [
    ...base,
    colorLine,
    `พก "${charm.item}" + ใช้เลขมงคล ${charm.number} (ตั้งเป็นจำนวนคน/เวลานัด)`,
  ];
};

// ===== โหมดเช็คความบาป =====
// meta: { nickname, element, zodiacName, sin, nameNum, dayColor, moon, seed }
export const sinFallback = (meta = {}) => {
  const { element = 'ดิน', zodiacName, sin = 50, nameNum = 5, dayColor = null, moon } = meta;
  const seed = meta.seed || `${meta.nickname || ''}:${zodiacName || ''}:${element}`;
  const b = bucket(sin);
  const parts = [
    pick(OPENER[b], seed, 'open'),
    pick(ELEM_INSIGHT[element] || ELEM_INSIGHT['ดิน'], seed, 'elem'),
  ];
  const zf = pick(ZODIAC_FLAVOR[zodiacGroup(zodiacName)], seed, 'zod');
  let analysis = `${parts[0]} ${parts[1]}${zf || ''}`;
  analysis += ` ${pick(NAME_QUIP[nameGroup(nameNum)], seed, 'name')}`;
  if (moon) analysis += ` ${MOON_LINE[moon.idx] || ''}`;
  analysis += ` ${pick(CLOSER[b], seed, 'close')} (บาปรวม ${sin}%)`;

  return {
    analysis,
    remedies: buildRemedies(element, seed, dayColor),
    charm: charmOf(element, seed),
    fallback: true,
  };
};

