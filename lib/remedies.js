// รับ element + seed + sin → รายการแก้เคล็ดตามระดับบาป
// ธาตุ pool ส่งมาจาก fallback.js (REMEDY_POOL) เพื่อไม่ให้ไฟล์นี้ซ้ำข้อมูล
export const buildRemedies = ({ element, seed, dayColor, sin, elemPool = [], extra = [] }) => {
  const tier = remedyTier(sin);
  const charm = charmOf(element, seed);
  const colorLine = dayColor
    ? `ใส่สีมงคลประจำวันเกิด (${dayColor.name}) หรือสี${charm.color.split(' ')[0]} วันเดินทาง`
    : `ใส่สีมงคล ${charm.color} วันเดินทาง`;
  const charmLine = `พก "${charm.item}" + ใช้เลขมงคล ${charm.number} (ตั้งเป็นจำนวนคน/เวลานัด)`;
  const [e1, e2] = pickN(elemPool, 2, seed, 'rem');
  const [c1, c2] = pickN(CONVENIENCE, 2, seed, 'conv');
  const [f1, f2] = pickN(FOLK, 2, seed, 'folk');

  const ordered = [
    pick(TIER_LEAD[tier.key], seed, 'lead'),
    c1, e1, colorLine, charmLine, f1, ...extra, e2, c2, f2,
  ].filter(Boolean);

  return { remedies: ordered.slice(0, tier.count), tier };
};
