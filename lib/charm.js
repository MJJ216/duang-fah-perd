// ===== ของขลัง / ไอเทม / สี / เลขมงคล ประจำตัว (seeded ต่อคน) =====
import { pick, luckyNumber } from './seed';

const CHARM_ITEMS = {
  น้ำ: ['ขวดน้ำแร่ใสติดเป้', 'เปลือกหอยเล็กๆ', 'หินสีฟ้ากลมๆ', 'สร้อยลูกปัดใส'],
  ไม้: ['ใบไม้มงคลอัดแห้ง', 'เมล็ดพืชห่อผ้า', 'ไม้หอมชิ้นเล็ก', 'ลูกประคำไม้'],
  ไฟ:  ['ไฟแช็กคู่ใจ', 'เทียนเล่มจิ๋ว', 'พริกแห้งมงคล', 'หินสีแดงส้ม'],
  ทอง: ['เหรียญนำโชค', 'กำไลโลหะ', 'กุญแจทองเหลือง', 'ระฆังเล็กกรุ๊งกริ๊ง'],
  ดิน: ['ก้อนหินจากดอยที่เคยพิชิต', 'ขมิ้นชันห่อผ้าเหลือง', 'ดินมงคลใส่ขวดจิ๋ว', 'ลูกแก้วสีน้ำตาล'],
};

// สีมงคลที่ counter ธาตุตัวเอง (ตามหลัก 5 ธาตุ) — ใส่แล้วช่วยกันฟ้าปิด
const LUCKY_COLOR = {
  น้ำ: 'แดง / ส้ม (ธาตุไฟข่มน้ำ)',
  ไม้: 'แดง (ไฟตัดวงจรไม้เรียกน้ำ)',
  ไฟ:  'ทอง / เหลือง (ย้ำพลังไฟ)',
  ทอง: 'ขาว / ทอง (เสริมธาตุตัวเอง)',
  ดิน: 'เหลือง / น้ำตาล (เสริมดินให้มั่นคง)',
};

// รับ element + seed → ของขลังประจำตัว (คงที่ต่อคน)
export const charmOf = (element, seed) => {
  const key = CHARM_ITEMS[element] ? element : 'ดิน';
  return {
    item: pick(CHARM_ITEMS[key], seed, 'charm'),
    color: LUCKY_COLOR[key],
    number: luckyNumber(seed, 'charm'),
  };
};
